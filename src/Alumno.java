public class Alumno {
    private int id;
    private String matricula;
    private String nombre;
    private String edad;
    private String sexo;
    private String correo;

    public Alumno(int id, String matricula, String nombre, String edad, String sexo, String correo) {
        this.id = id;
        this.matricula = matricula;
        this.nombre = nombre;
        this.edad = edad;
        this.sexo = sexo;
        this.correo = correo;
    }
}
